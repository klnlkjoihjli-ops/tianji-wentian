// 意图识别
export function detectScene(q: string): string {
  // 兵法谋略优先检测（避免被"竞争""战争"误判到时事）
  if (/孙子|六韬|三略|兵法|谋略|谋攻|奇正|虚实|用间|知彼知己|上兵伐谋|兵者/.test(q)) return 'H'
  // 儒家修身优先于道家（避免"仁义""礼"被误判）
  if (/论语|孔子|孟子|儒家|大学|中庸|修身|齐家|仁义|荀子|礼记|君子之道|德行/.test(q)) return 'G'
  // 养生医学
  if (/失眠|焦虑|疲劳|养生|脏腑|调养|补气|气血|阴虚|阳虚|体质|中医|睡眠|头疼|肝火|脾虚|肺|肾虚|心火/.test(q)) return 'B'
  // 时事天机
  if (/时事|局势|全球|经济形势|战争|科技|2025|2026|趋势|AI|国际|地缘|政治|外交|股市/.test(q)) return 'C'
  // 易经起卦
  if (/起卦|占卦|卦象|摇卦|易经问/.test(q)) return 'D'
  // 节气养生
  if (/节气|时辰|罗盘|春分|夏至|秋分|冬至|立春|立夏|立秋|立冬|芒种|清明|节令/.test(q)) return 'E'
  // 道家智慧
  if (/道德经|庄子|道家|老子|无为|逍遥|智慧|选择|决策|困惑|迷茫|意义|人生/.test(q)) return 'F'
  return 'A'
}
