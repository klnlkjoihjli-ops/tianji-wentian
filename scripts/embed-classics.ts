async function main() {
  console.log('🚀 开始完整典籍向量化...')
  console.log(`📚 共 ${ALL_CLASSICS.length} 条典籍待处理`)

  // 清空旧数据
  await supabase.from('classics').delete().gte('id', 0)
  console.log('🗑 已清空旧数据')

  let success = 0, failed = 0
  const batch: object[] = []

  for (let i = 0; i < ALL_CLASSICS.length; i++) {
    const item = ALL_CLASSICS[i]
    process.stdout.write(`\r处理中: ${i + 1}/${ALL_CLASSICS.length} ✓${success} ✗${failed}  `)

    try {
      const embedding = await embed(item.content)
      batch.push({ ...item, embedding })

      if (batch.length >= 5) {
        await insertBatch([...batch])
        success += batch.length
        batch.length = 0
      }

      await new Promise(r => setTimeout(r, 150))
    } catch (e) {
      failed++
      console.error(`\n✗ 失败: ${item.source}·${item.chapter}`, (e as Error).message)
    }
  }

  if (batch.length > 0) {
    await insertBatch(batch)
    success += batch.length
  }

  console.log(`\n✅ 完成！成功: ${success} 条，失败: ${failed} 条`)
}

main().catch(console.error)
